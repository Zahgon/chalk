// Command gen writes styles_gen.go, which exposes every entry in the ANSI
// style table as a method on Style and *Instance and as a package-level
// function.
//
// The style table in package ansistyles is the single source of truth. Run it
// with `go generate ./...`.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"strings"
	"unicode"

	"github.com/chalk/chalk-go/ansistyles"
)

func main() {
	log.SetFlags(0)
	log.SetPrefix("gen: ")

	output := flag.String("o", "styles_gen.go", "output file")
	flag.Parse()

	source, err := generate()
	if err != nil {
		log.Fatal(err)
	}

	if err := os.WriteFile(*output, source, 0o644); err != nil {
		log.Fatal(err)
	}

	fmt.Printf("wrote %s (%d styles)\n", *output, len(ansistyles.All))
}

// aliases documents the styles that are spelled two ways.
var aliases = map[string]string{
	"gray":                 "blackBright",
	"grey":                 "blackBright",
	"bgGray":               "bgBlackBright",
	"bgGrey":               "bgBlackBright",
	"underlineGray":        "underlineBlackBright",
	"underlineGrey":        "underlineBlackBright",
	"underlineBlackBright": "",
}

// descriptions overrides the generated summary where the style name alone is
// not self-explanatory.
var descriptions = map[string]string{
	"reset":           "resets all styles",
	"bold":            "renders text in bold, which many terminals show as a brighter color",
	"dim":             "renders text dimmed",
	"italic":          "renders text in italics, which is not widely supported",
	"underline":       "underlines text",
	"underlineDouble": "underlines text with a double line",
	"underlineCurly":  "underlines text with a curly line, commonly used to mark errors",
	"underlineDotted": "underlines text with a dotted line",
	"underlineDashed": "underlines text with a dashed line",
	"overline":        "draws a line above text, which is not widely supported",
	"inverse":         "swaps the foreground and background colors",
	"hidden":          "hides text while keeping it selectable, useful for passwords",
	"strikethrough":   "draws a line through text, which is not widely supported",
}

func exported(name string) string {
	runes := []rune(name)
	runes[0] = unicode.ToUpper(runes[0])

	return string(runes)
}

// summary produces the sentence that follows the method name in its doc
// comment.
func summary(style ansistyles.Style) string {
	if text, ok := descriptions[style.Name]; ok {
		return text
	}

	switch style.Group {
	case ansistyles.GroupColor:
		return "sets the foreground color to " + colorPhrase(style.Name, "")
	case ansistyles.GroupBgColor:
		return "sets the background color to " + colorPhrase(style.Name, "bg")
	case ansistyles.GroupUnderlineColor:
		return "sets the underline color to " + colorPhrase(style.Name, "underline")
	default:
		return "applies the " + style.Name + " style"
	}
}

// colorPhrase turns a style name such as "bgRedBright" into "bright red".
func colorPhrase(name, prefix string) string {
	base := strings.TrimPrefix(name, prefix)
	if prefix != "" {
		base = strings.ToLower(base[:1]) + base[1:]
	}

	switch base {
	case "gray", "grey":
		return base
	}

	if strings.HasSuffix(base, "Bright") {
		return "bright " + strings.TrimSuffix(base, "Bright")
	}

	return base
}

func generate() ([]byte, error) {
	var buf bytes.Buffer

	fmt.Fprint(&buf, `// Code generated by "go run ./gen". DO NOT EDIT.

package chalk

import "github.com/chalk/chalk-go/ansistyles"

// mustStyle resolves a style that the generator proved exists.
func mustStyle(name string) ansistyles.Style {
	style, ok := ansistyles.Lookup(name)
	if !ok {
		panic("chalk: missing style " + name)
	}

	return style
}

// Resolved table entries, bound once at start-up.
var (
`)

	for _, style := range ansistyles.All {
		fmt.Fprintf(&buf, "\tstyle%s = mustStyle(%q)\n", exported(style.Name), style.Name)
	}

	fmt.Fprint(&buf, ")\n")

	// Methods on Style.
	fmt.Fprint(&buf, "\n// Style methods.\n")

	for _, style := range ansistyles.All {
		name := exported(style.Name)
		writeDoc(&buf, name, summary(style), style.Name)
		fmt.Fprintf(&buf, "func (s Style) %s() Style {\n\treturn s.with(style%s.Open, style%s.Close)\n}\n\n", name, name, name)
	}

	// Methods on *Instance, so a chain can start from a custom instance.
	fmt.Fprint(&buf, "// Instance methods. Each starts a chain bound to the instance.\n\n")

	for _, style := range ansistyles.All {
		name := exported(style.Name)
		fmt.Fprintf(&buf, "// %s starts a chain that %s.\nfunc (i *Instance) %s() Style {\n\treturn i.Root().%s()\n}\n\n",
			name, summary(style), name, name)
	}

	for _, model := range models {
		fmt.Fprintf(&buf, "// %s starts a chain that %s.\nfunc (i *Instance) %s(%s) Style {\n\treturn i.Root().%s(%s)\n}\n\n",
			model.name, model.summary, model.name, model.params, model.name, model.args)
	}

	fmt.Fprint(&buf, "// Visible starts a chain that only renders when colors are enabled.\nfunc (i *Instance) Visible() Style {\n\treturn i.Root().Visible()\n}\n\n")
	fmt.Fprint(&buf, "// By starts a chain with the style registered under an ANSI style name.\nfunc (i *Instance) By(name string) (Style, error) {\n\treturn i.Root().By(name)\n}\n\n")

	// Package-level functions, rendering through Default.
	fmt.Fprint(&buf, "// Package-level functions. Each starts a chain bound to Default.\n\n")

	for _, style := range ansistyles.All {
		name := exported(style.Name)
		fmt.Fprintf(&buf, "// %s starts a chain that %s.\nfunc %s() Style {\n\treturn Default.Root().%s()\n}\n\n",
			name, summary(style), name, name)
	}

	for _, model := range models {
		fmt.Fprintf(&buf, "// %s starts a chain that %s.\nfunc %s(%s) Style {\n\treturn Default.Root().%s(%s)\n}\n\n",
			model.name, model.summary, model.name, model.params, model.name, model.args)
	}

	fmt.Fprint(&buf, "// Visible starts a chain that only renders when colors are enabled.\nfunc Visible() Style {\n\treturn Default.Root().Visible()\n}\n\n")
	fmt.Fprint(&buf, "// By starts a chain with the style registered under an ANSI style name.\nfunc By(name string) (Style, error) {\n\treturn Default.Root().By(name)\n}\n")

	return format.Source(buf.Bytes())
}

// models lists the parameterized color styles, which are hand-written on Style
// and only forwarded here.
var models = []struct {
	name    string
	params  string
	args    string
	summary string
}{
	{"RGB", "r, g, b uint8", "r, g, b", "sets a 24-bit foreground color, downsampling if needed"},
	{"BgRGB", "r, g, b uint8", "r, g, b", "sets a 24-bit background color, downsampling if needed"},
	{"UnderlineRGB", "r, g, b uint8", "r, g, b", "sets a 24-bit underline color, downsampling if needed"},
	{"Hex", "hex string", "hex", "sets a foreground color from a hex string"},
	{"BgHex", "hex string", "hex", "sets a background color from a hex string"},
	{"UnderlineHex", "hex string", "hex", "sets an underline color from a hex string"},
	{"Ansi256", "code uint8", "code", "sets a foreground color from the 256-color palette"},
	{"BgAnsi256", "code uint8", "code", "sets a background color from the 256-color palette"},
	{"UnderlineAnsi256", "code uint8", "code", "sets an underline color from the 256-color palette"},
}

func writeDoc(buf *bytes.Buffer, goName, text, jsName string) {
	fmt.Fprintf(buf, "// %s %s.\n", goName, text)

	if target, ok := aliases[jsName]; ok && target != "" {
		fmt.Fprintf(buf, "//\n// It is an alias of %s.\n", exported(target))
	}
}
